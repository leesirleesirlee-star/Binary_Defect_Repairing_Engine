export function label(locale, key, count) {
  if (locale !== 'en' && locale !== 'zh-Hans') {
    const translated = extraCopy[locale]?.[key];
    if (typeof translated === 'function') return translated(count);
    if (typeof translated === 'string') return translated;
  }
  const value = copy[key]?.[locale === 'zh-Hans' ? 1 : 0] ?? key;
  return typeof value === 'function' ? value(count) : value;
}
